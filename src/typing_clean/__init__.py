"""
You like type-hinted python, but you hate how much **EVERY** module's namespace is cluttered with ``typing`` objects?
If so, then instead of importing from ``typing`` or ``typing_extensions``, import from ``typing_clean``:

- It's a union of both ``typing`` and ``typing_extensions``. No need to import some classes from here and some - from there.
- The same classes are available, just their names prefixed with underscores (``Iterable`` -> ``_Iterable``).
- The most used ones also have short alias (``_C`` for ``_Callable``, ``_U`` for ``_Union``, ...).
- +3 extra copies of common TypeVars:

  - Not only ``_T``, but also ``_T2``, ``_T3``, ``_T4``.
  - Same for ``_KT``, ``_VT``, ``_T_contra``, ``_P``.

Wildcard import works, too::

	from typing_clean import *
"""
